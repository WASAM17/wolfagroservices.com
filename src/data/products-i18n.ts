// ─── Catalogue localisé ──────────────────────────────────────────────────────

const catalog: Record<string, Product[]> = { fr, en, de, zh };

export const getLocalizedProducts = (locale: string): Product[] =>
  catalog[locale] ?? catalog.fr;

export const getLocalizedProductBySlug = (slug: string, locale: string): Product | undefined =>
  getLocalizedProducts(locale).find((p) => p.slug === slug);

export const getLocalizedProductById = (id: string, locale: string): Product | undefined =>
  getLocalizedProducts(locale).find((p) => p.id === id);
